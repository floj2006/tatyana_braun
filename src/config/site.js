/** Пропускает только https-ссылки на разрешённые хосты, иначе возвращает ''. */
export function safeUrl(url, hosts) {
  try {
    const u = new URL(url);
    return u.protocol === 'https:' && hosts.includes(u.hostname) ? u.href : '';
  } catch {
    return '';
  }
}

